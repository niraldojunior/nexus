export const LEGACY_TABLE_NAMES = Object.keys(TABLE_RENAMES) as LegacyTableName[];

const LEGACY_BY_CANONICAL = new Map<string, LegacyTableName>(
  Object.entries(TABLE_RENAMES).map(([legacy, canonical]) => [canonical, legacy as LegacyTableName]),
);

export const legacyTableName = (canonical: string): LegacyTableName | undefined =>
  LEGACY_BY_CANONICAL.get(canonical);

export const canonicalTableName = (legacy: LegacyTableName): ManagedTableName =>
  TABLE_RENAMES[legacy];

export const databaseDomainOf = (table: string): DatabaseDomain => {
  const domain = table.split('_', 1)[0] as DatabaseDomain;
  if (!DATABASE_DOMAINS.includes(domain)) {
    throw new Error(`Tabela sem domínio canônico: ${table}.`);
  }
  return domain;
};
